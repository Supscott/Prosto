#!/usr/bin/env node
// Builds the static uBlock Origin scriptlet bundle and the adblock-rust stub resources (CB-09).
//
//   node tools/build_scriptlets.mjs            download the pinned uBO tag, rebuild both outputs
//   node tools/build_scriptlets.mjs --src DIR  same, from an already extracted uBO source tree
//   node tools/build_scriptlets.mjs --check    offline: committed outputs match the recorded hashes
//   node tools/build_scriptlets.mjs --update-hashes   rebuild and rewrite the hash constants below
//
// Outputs (never edit by hand):
//   app/src/main/assets/scripts/scriptlets.js     function expression returning a frozen name map
//   tools/filterlists/scriptlet_stubs.json        adblock-rust template resources (data, not code)

import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const UBO_TAG = '1.76.2';
const UBO_TARBALL_SHA256 = '10d9a1f2436dc9fd56468dafe607fbb714198dd5b68196df445c604abf7d8171';
const BUNDLE_SHA256 = 'aa30ca2e5d30b22f6f485d64229d37b70d0e133b9b213acf0d117124b9b4f5ca';
const STUBS_SHA256 = '56ddc0b70401ff6283709803a1bc6a9c7bb0700d3396c778b926563f87713a33';

const MAX_ARGS = 10;
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const BUNDLE_PATH = join(ROOT, 'app/src/main/assets/scripts/scriptlets.js');
const STUBS_PATH = join(ROOT, 'tools/filterlists/scriptlet_stubs.json');
const SELF_PATH = fileURLToPath(import.meta.url);

const sha256 = (data) => createHash('sha256').update(data).digest('hex');
const die = (msg) => { console.error(`build_scriptlets: ${msg}`); process.exit(1); };

const bareName = (n) => (n.endsWith('.js') ? n.slice(0, -3) : n);

/** Selects the scriptlets we can run from a document-start script and orders them. */
export function selectScriptlets(all) {
    const byName = new Map(all.map((s) => [s.name, s]));
    const skipped = [];
    const kept = [];
    for (const s of all) {
        if (s.name.endsWith('.fn')) { continue; }
        // uBO forgot the flag on trusted-prevent-xhr; every trusted-* name is trusted-only.
        if (s.requiresTrust === true || s.name.startsWith('trusted-')) { skipped.push([s.name, 'requires trust']); continue; }
        if (s.world && s.world !== 'MAIN') { skipped.push([s.name, `${s.world} world`]); continue; }
        kept.push(s);
    }
    kept.sort((a, b) => a.name.localeCompare(b.name));
    // Transitive dependency closure, each helper emitted once.
    const helpers = new Map();
    const visit = (name, owner) => {
        const d = byName.get(name);
        if (d === undefined) { die(`${owner} depends on unknown ${name}`); }
        if (helpers.has(name)) { return; }
        helpers.set(name, d);
        for (const dep of d.dependencies ?? []) { visit(dep, d.name); }
    };
    for (const s of kept) {
        helpers.set(s.name, s);
        for (const dep of s.dependencies ?? []) { visit(dep, s.name); }
    }
    return { kept, skipped, functions: [...helpers.values()].sort((a, b) => a.name.localeCompare(b.name)) };
}

/** All lookup keys for a scriptlet: canonical (no `.js`), `.js` form, and uBO aliases. */
export function keysOf(s) {
    const keys = new Set([bareName(s.name), s.name]);
    for (const a of s.aliases ?? []) { keys.add(bareName(a)); keys.add(a); }
    return [...keys];
}

export function buildBundle(all, tag) {
    const { kept, skipped, functions } = selectScriptlets(all);
    const seenFnNames = new Map();
    const decls = functions.map((s) => {
        const code = s.fn.toString().trim();
        if (!/^(async\s+)?function\b|^class\b/.test(code)) { die(`${s.name}: unsupported declaration shape`); }
        if (!s.fn.name) { die(`${s.name}: anonymous function`); }
        if (seenFnNames.has(s.fn.name)) { die(`function name clash: ${s.fn.name} (${s.name}, ${seenFnNames.get(s.fn.name)})`); }
        seenFnNames.set(s.fn.name, s.name);
        return code;
    });
    const owners = new Map();
    const entries = [];
    for (const s of kept) {
        for (const key of keysOf(s)) {
            if (owners.has(key) && owners.get(key) !== s.name) { die(`alias clash: ${key}`); }
            owners.set(key, s.name);
            entries.push(`    [${JSON.stringify(key)}, ${s.fn.name}],`);
        }
    }
    const text = `/*
 * Prosto scriptlet bundle. GENERATED by tools/build_scriptlets.mjs, do not edit.
 *
 * Contains scriptlet code from uBlock Origin ${tag}
 * https://github.com/gorhill/uBlock
 * Copyright (C) 2014-present Raymond Hill
 * Licensed under the GNU General Public License v3.0 or later.
 *
 * This file is one function expression and runs nothing by itself. Use it as
 *     const scriptlets = (<contents of this file>)();
 * It returns a frozen map: scriptlet name or alias (with and without ".js") -> function(...args).
 * The engine supplies only names and string arguments; no code is ever evaluated from a string.
 * Everything lives in the closure, no global is defined or read except ones the scriptlets
 * themselves touch when they run (as in uBO).
 */
(function prostoScriptlets() {
const scriptletGlobals = {};

${decls.join('\n\n')}

const table = new Map([
${entries.join('\n')}
]);
return Object.freeze(Object.fromEntries(table));
})
`;
    return { text, kept, skipped };
}

export function buildStubs(kept, tag) {
    const resources = kept.map((s) => {
        const canonical = bareName(s.name);
        const args = Array.from({ length: MAX_ARGS }, (_, i) => `"{{${i + 1}}}"`).join(',');
        const body = `["${canonical}",${args}]`;
        const aliases = keysOf(s).filter((k) => k !== s.name);
        return { name: s.name, aliases, kind: 'template', content: Buffer.from(body).toString('base64') };
    });
    const doc = {
        _format: [
            'GENERATED by tools/build_scriptlets.mjs from uBlock Origin ' + tag + '. Do not edit.',
            'Each entry is an adblock-rust Resource: {name, aliases, kind, content}.',
            'kind "template": content is base64 of a JSON array body',
            `["<canonical scriptlet name>","{{1}}","{{2}}",...,"{{${MAX_ARGS}}}"] with ${MAX_ARGS} argument slots.`,
            'The engine fills {{n}} with the filter arguments of ##+js(name, a1, a2, ...) and the native',
            'wrapper parses the resulting injected_script text back into [name, arg1, ...], dropping',
            'unfilled {{n}} slots. The name is the key into the scriptlets.js bundle map.',
            'The format is provisional until CB-01 fixes the native parser.',
        ],
        resources,
    };
    return JSON.stringify(doc, null, 2) + '\n';
}

async function loadUbo(srcDir) {
    const mod = await import(pathToFileURL(join(srcDir, 'src/js/resources/scriptlets.js')).href);
    return mod.builtinScriptlets;
}

async function downloadUbo() {
    const url = `https://github.com/gorhill/uBlock/archive/refs/tags/${UBO_TAG}.tar.gz`;
    const res = await fetch(url);
    if (!res.ok) { die(`download failed: ${res.status} ${url}`); }
    const buf = Buffer.from(await res.arrayBuffer());
    const got = sha256(buf);
    if (got !== UBO_TARBALL_SHA256) { die(`tarball sha256 mismatch: ${got}`); }
    const dir = mkdtempSync(join(tmpdir(), 'ubo-'));
    const tgz = join(dir, 'ubo.tar.gz');
    const src = join(dir, 'src');
    mkdirSync(src);
    writeFileSync(tgz, buf);
    execFileSync('tar', ['xzf', tgz, '-C', src, '--strip-components=1']);
    return src;
}

function check() {
    let bad = 0;
    for (const [path, want] of [[BUNDLE_PATH, BUNDLE_SHA256], [STUBS_PATH, STUBS_SHA256]]) {
        let got;
        try { got = sha256(readFileSync(path)); } catch { got = 'missing'; }
        if (got !== want) { console.error(`stale or missing: ${path}`); bad++; }
    }
    if (bad) { die('run: node tools/build_scriptlets.mjs --update-hashes'); }
    console.log(`scriptlets bundle and stubs match uBO ${UBO_TAG}`);
}

async function main() {
    const args = process.argv.slice(2);
    if (args.includes('--check')) { return check(); }
    const si = args.indexOf('--src');
    const src = si >= 0 ? resolve(args[si + 1]) : await downloadUbo();
    const all = await loadUbo(src);
    const { text, kept, skipped } = buildBundle(all, UBO_TAG);
    const stubs = buildStubs(kept, UBO_TAG);
    writeFileSync(BUNDLE_PATH, text);
    writeFileSync(STUBS_PATH, stubs);
    const hashes = { BUNDLE_SHA256: sha256(text), STUBS_SHA256: sha256(stubs) };
    console.log(`uBO ${UBO_TAG}: ${kept.length} scriptlets, ${skipped.length} skipped, bundle ${text.length} bytes`);
    for (const [n, why] of skipped) { console.log(`  skipped ${n}: ${why}`); }
    if (args.includes('--update-hashes')) {
        let self = readFileSync(SELF_PATH, 'utf8');
        for (const [k, v] of Object.entries(hashes)) {
            self = self.replace(new RegExp(`const ${k} = '[0-9a-f]{64}';`), `const ${k} = '${v}';`);
        }
        writeFileSync(SELF_PATH, self);
    } else if (hashes.BUNDLE_SHA256 !== BUNDLE_SHA256 || hashes.STUBS_SHA256 !== STUBS_SHA256) {
        die('outputs differ from the recorded hashes; rerun with --update-hashes if intended');
    }
}

if (process.argv[1] && resolve(process.argv[1]) === SELF_PATH) { await main(); }
